#!/usr/bin/env python3
"""Regenerate model-specific boundary relaxations for A (D A)^k, k=0,1,2.

Adapted from experiment 19's factor_method/lloh_rounds/local_bound.py.
Each interval event contributes an opening and a closing boundary. Relax
compatibility between boundaries, minimize each boundary independently, sum,
and divide by two (rounding up) to obtain an admissible event-count bound.
L_LOH permits interval loss depth beyond CN when output reaches zero; gain
is its non-resurrecting counterpart. WGD charges are added outside these tables.
"""
import argparse
import itertools
from pathlib import Path
import re
import numpy as np
ROOT = Path(__file__).resolve().parents[1]
INF = 10000


def minplus(a, b):
    out = np.full((len(a), b.shape[1]), INF, dtype=np.int32)
    for k in range(a.shape[1]):
        np.minimum(out, a[:, k:k+1] + b[k:k+1, :], out=out)
    return out


def interval(source, target, exclude_zero):
    if exclude_zero:
        if source == target == 0:
            return 0, 9
        if source > 0 and 0 < target <= source:
            return source-target, source-target
        return None
    if target > source:
        return None
    return (source, 8) if target == 0 else (source-target, source-target)


def primitive(states, exclude_zero):
    out = np.full((len(states), len(states)), INF, dtype=np.int32)
    for i, source in enumerate(states):
        for j, target in enumerate(states):
            caps = [interval(s, t, exclude_zero) for s, t in zip(source, target)]
            if any(c is None for c in caps):
                continue
            if len(source) == 1:
                out[i, j] = caps[0][0]
            else:
                (lo, hi), (lo2, hi2) = caps
                out[i, j] = max(0, lo-hi2, lo2-hi)
    return out


def tables(endpoint, capped):
    states = list(itertools.product(range(9), repeat=1 if endpoint else 2))
    ids = {s: i for i, s in enumerate(states)}
    a = minplus(primitive(states, False), primitive(states, True).T)
    d = np.full_like(a, INF)
    for i, source in enumerate(states):
        if capped or max(source) <= 4:
            target = tuple(min(8, 2*c) for c in source)
            d[i, ids[target]] = 0
    branches = [a]
    for _ in range(2):
        branches.append(minplus(minplus(branches[-1], d), a))
    return np.stack([minplus(x.T, y) for x in branches for y in branches])


def read_rows(text, name, width):
    body = text.split(f'{name}[9][{width}] = {{\n', 1)[1].split('\n};', 1)[0]
    return np.array([[int(v) for v in re.findall(r'\d+', line)] for line in body.splitlines()])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check-strict', type=Path, help='Check strict regeneration against a parent-branch chromosome_bound.hpp')
    args = parser.parse_args()
    headers = [ROOT/'medicc/cext/full_fst'/engine/'src/generated/chromosome_bound.hpp'
               for engine in ['ancestors', 'direct_pair', 'reference_pair']]
    if args.check_strict:
        original = args.check_strict.read_text()
        for name, endpoint in [('END', True), ('EDGE', False)]:
            table = tables(endpoint, False).reshape(9, -1)
            np.testing.assert_array_equal(table, read_rows(original, name, table.shape[1]))
        print('PASS: strict generator reproduces all 59,778 parent table entries', flush=True)
    # Preserve the existing message-layout DP; only its model constants change.
    suffix = headers[0].read_text().split('// Relax message paths', 1)[1]
    text = '// Generated by scripts/generate_chromosome_bound.py.\n'
    text += '// Capped D(c)=min(2*c,8); branch index 3*ka+kb. WGD costs excluded.\n'
    text += '#pragma once\nnamespace chromosome_bound {\n'
    for name, endpoint in [('END', True), ('EDGE', False)]:
        table = tables(endpoint, True).reshape(9, -1)
        assert 0 <= table.min() <= table.max() < 255
        text += f'static constexpr unsigned char {name}[9][{table.shape[1]}] = {{\n'
        text += ''.join(' {' + ','.join(map(str, row)) + '},\n' for row in table)
        text += '};\n'
    text += '\n// Relax message paths' + suffix
    for path in headers:
        path.write_text(text)
    print('Wrote capped boundary tables to all three engines', flush=True)


if __name__ == '__main__':
    main()
